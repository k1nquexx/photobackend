-- Схема базы данных для продакшн-окружения
-- Предотвращает потерю структуры и данных при перезапуске (заменяет Hibernate ddl-auto=create/drop)

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(64) NOT NULL,
    client_name VARCHAR(255) NOT NULL,
    client_phone VARCHAR(50) NOT NULL,
    details VARCHAR(4000),
    total_price DECIMAL(12, 2) NOT NULL,
    booking_date VARCHAR(20),
    booking_time VARCHAR(20),
    status VARCHAR(50) NOT NULL,
    download_url VARCHAR(2000),
    promo_code VARCHAR(50),
    tracking_token VARCHAR(64),
    created_at VARCHAR(50),
    client_ip VARCHAR(50),
    CONSTRAINT uk_booking_public_id UNIQUE (public_id),
    CONSTRAINT uk_booking_tracking_token UNIQUE (tracking_token)
);

CREATE INDEX IF NOT EXISTS idx_booking_public_id ON bookings (public_id);
CREATE INDEX IF NOT EXISTS idx_booking_tracking_token ON bookings (tracking_token);
CREATE INDEX IF NOT EXISTS idx_booking_status ON bookings (status);
CREATE INDEX IF NOT EXISTS idx_booking_date_time ON bookings (booking_date, booking_time);

CREATE TABLE IF NOT EXISTS time_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_date VARCHAR(20) NOT NULL,
    slot_time VARCHAR(20) NOT NULL,
    is_booked BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_timeslot_date_time UNIQUE (slot_date, slot_time)
);

CREATE INDEX IF NOT EXISTS idx_timeslot_date_booked ON time_slots (slot_date, is_booked);
CREATE INDEX IF NOT EXISTS idx_timeslot_date_time ON time_slots (slot_date, slot_time);
CREATE INDEX IF NOT EXISTS idx_timeslot_booked ON time_slots (is_booked);

CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name VARCHAR(100) NOT NULL,
    rating INT NOT NULL,
    comment VARCHAR(2000) NOT NULL,
    created_at VARCHAR(50),
    approved BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_reviews_approved ON reviews (approved, id);
